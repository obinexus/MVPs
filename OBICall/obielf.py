class OBIELFMarshall:
    """Enhanced marshalling for OBIELF artifact generation"""
    
    def __init__(self, dop_adapter, consciousness_threshold=0.954):
        self.dop_adapter = dop_adapter
        self.threshold = consciousness_threshold
        self.stats = {'generated': 0, 'consciousness_validated': 0}
    
    def marshall_to_obielf(self, task, name="obiapp", consciousness_level=0.0, **kwargs):
        """Marshall task data to complete OBIELF artifact bundle"""
        
        # Process through existing DOP adapter
        processed = self.dop_adapter.process(task, kwargs.get('context'))
        
        # Generate OBIELF artifact bundle
        builder = OBIELFBuilder(consciousness_threshold=self.threshold)
        
        obielf_bundle = {
            f"{name}.obielf.asm": builder.generate_obielf_main(name, consciousness_level, processed),
            f"Makefile": builder.generate_obielf_makefile(name),
            f"{name}.obielf.dat": json.dumps(processed, indent=2),
            f"OBIELF_COMPLIANCE.md": builder.generate_obielf_spec_compliance(name, consciousness_level),
        }
        
        # Add consciousness validation metadata
        obielf_metadata = {
            'obielf_generated': True,
            'consciousness_level': consciousness_level,
            'threshold_met': consciousness_level >= self.threshold,
            'build_uuid': builder.build_uuid,
            'architecture': builder.architecture,
            'generated_artifacts': list(obielf_bundle.keys())
        }
        
        # Update stats
        self.stats['generated'] += 1
        if consciousness_level >= self.threshold:
            self.stats['consciousness_validated'] += 1
        
        # Package in OBIPickle for transmission
        return OBIPickle(
            data=obielf_bundle, 
            metadata={**processed.get('processing_metadata', {}), **obielf_metadata},
            consciousness_level=consciousness_level
        )

